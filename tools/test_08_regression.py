import tempfile,shutil,subprocess,struct
from pathlib import Path
from vm_harness import VM,ROOT
from fs_format import validate,extract_or_migrate,SIZE,put,seal
checks=[]
def ok(m):checks.append(m);print('OK:',m,flush=True)
with tempfile.TemporaryDirectory() as t:
 p=Path(t);d=p/'data.img';shutil.copyfile(ROOT/'build/asfs4.img',d)
 v=VM(p,d)
 try:
  assert 'ASFS v4' in v.out()
  v.cmd('memtest','Memoria: OK')
  v.cmd('drvnew demo.drv','Guardado en disco')
  v.cmd('drvload demo.drv','MiniDRV activado')
  v.cmd('drivers','demo ready text')
  v.cmd('drvread demo','Hola desde MiniDRV')
  v.cmd('drvwrite demo Prueba interna','14 bytes escritos')
  v.cmd('drvread demo','Prueba interna')
  v.cmd('drvload demo.drv','error=4')
  v.cmd('drvread demo','Prueba interna')
  v.cmd('drvunload vga','error=3')
  v.cmd('drvunload demo','MiniDRV retirado')
  v.cmd('drvread demo','error=1')
  v.cmd('write cuenta.drv name cuenta')
  v.cmd('append cuenta.drv type counter')
  v.cmd('drvload cuenta.drv','MiniDRV activado')
  v.cmd('drvread cuenta','\n0\n');v.cmd('drvread cuenta','\n1\n')
  v.cmd('drvwrite cuenta','0 bytes escritos');v.cmd('drvread cuenta','\n0\n')
  v.cmd('write malo.drv name malo');v.cmd('append malo.drv type inventado')
  v.cmd('drvload malo.drv','Fuente MiniDRV invalido')
  v.cmd('write fijo.drv name fijo');v.cmd('append fijo.drv type text');v.cmd('append fijo.drv text Constante')
  v.cmd('drvload fijo.drv','MiniDRV activado');v.cmd('drvread fijo','Constante');v.cmd('drvwrite fijo cambio','error=2')
  v.cmd('mkdir carpeta');v.cmd('write /carpeta/a.txt Contenido')
  v.cmd('asm demo.asm demo.app','Ensamblado');v.cmd('run demo.app','EAX=42')
 finally:v.close()
 ok('MiniDRV: crear, activar, echo, contador, descargar, duplicados y proteccion de builtins')
 data=validate(d.read_bytes());assert data[:4]==b'ASF4'
 v=VM(p,d)
 try:
  v.cmd('cat /carpeta/a.txt','Contenido');v.cmd('drvread cuenta','error=1')
  v.cmd('drvload cuenta.drv','MiniDRV activado');v.cmd('drvread cuenta','\n0\n')
 finally:v.close()
 ok('Fuentes y carpetas persistentes; activacion explicita tras reinicio')
 # Archivo de 8000 bytes y una entrada por encima del limite antiguo.
 put(data,200,'grande.txt',b'x'*8000);seal(data)
 raw=bytearray(d.read_bytes());raw[:len(data)]=data;raw[8192*512:8192*512+len(data)]=data;d.write_bytes(raw)
 v=VM(p,d)
 try:
  v.cmd('ls','grande.txt 8000')
  v.cmd('append grande.txt x','8000 bytes')
  start=len(v.out());v.type('nano grande.txt');v.key('ret');v.wait('ASM nano | ',start)
  v.key('ctrl-x');v.wait('asm:/ > ',start)
 finally:v.close()
 raw=bytearray(d.read_bytes());raw[600]^=1;d.write_bytes(raw)
 v=VM(p,d)
 try:v.cmd('cat /carpeta/a.txt','Contenido');assert 'copia recuperada' in v.out()
 finally:v.close()
 ok('AFS4: archivo de 8000 bytes, entrada 200, editor y recuperacion de copia')
 old=extract_or_migrate((ROOT/'build/asfs2.img').read_bytes());validate(old)
 ok('Migracion de AFS2 conservando archivos y carpetas')
 host=p/'hdd.img';subprocess.run(['python3','tools/install_disk.py',str(host),'--data',str(d)],cwd=ROOT,check=True)
 v=VM(p,host,boot_disk=True)
 try:v.cmd('cat /carpeta/a.txt','Contenido');v.cmd('drvload demo.drv','MiniDRV activado')
 finally:v.close()
 ok('Disco GRUB arranca sin ISO con AFS4 y fuentes de drivers')
 target=p/'blank.img';target.write_bytes(bytes(32*1024*1024))
 v=VM(p,target)
 try:
  start=len(v.out());v.type('install hda');v.key('ret');v.wait('FORMAT hda',start)
  v.type('FORMAT hda');v.key('ret');v.wait('Formateado e instalado',start);v.wait('asm:/ > ',start)
  v.cmd('write nuevo.txt AFS4 instalado','Guardado en disco')
 finally:v.close()
 v=VM(p,target,boot_disk=True)
 try:v.cmd('cat nuevo.txt','AFS4 instalado')
 finally:v.close()
 ok('Instalador Live formatea ASFS4 y arranca GRUB sin CD')
(ROOT/'docs/VALIDACION_REGRESION_0.8.txt').write_text('\n'.join(checks)+'\n')
