"""Generate compact NASM seeding code from the short on-disk guides."""
from pathlib import Path
root = Path(__file__).resolve().parent.parent
files = sorted((root/'docs/on_disk').glob('*.TXT'))
assert 1 <= len(files) <= 16
out = ['; Generated by tools/generate_installed_docs.py.', 'fs_seed_docs:',
       '    pushad', '    mov edi, RECORDS+2*RSIZE',
       '    mov esi, fs_docs_name', '    mov ecx, 5', '    rep movsb',
       '    mov dword [RECORDS+2*RSIZE+RPARENT], ROOT_ID',
       '    mov dword [RECORDS+2*RSIZE+RKIND], 2',
       '    mov ebx, 5', '    mov ebp, fs_doc_table',
       '.next:', '    mov edi, ebx', '    shl edi, 13', '    add edi, RECORDS',
       '    mov edx, edi', '    mov esi, [ebp]', '    mov ecx, [ebp+4]',
       '    rep movsb', '    mov dword [edx+RPARENT], 2',
       '    mov dword [edx+RKIND], 1', '    mov ecx, [ebp+12]',
       '    mov [edx+RLEN], ecx', '    lea edi, [edx+RDATA]',
       '    mov esi, [ebp+8]', '    rep movsb',
       '    add ebp, 16', '    inc ebx', f'    cmp ebx, {5+len(files)}',
       '    jb .next',
       '    mov edi, RECORDS+25*RSIZE', '    mov dword [edi], 0x0062696c',
       '    mov dword [edi+RPARENT], ROOT_ID', '    mov dword [edi+RKIND], 2',
       '    mov edi, RECORDS+26*RSIZE', '    mov dword [edi], 0x692e6f69', '    mov word [edi+4], 0x636e',
       '    mov dword [edi+RPARENT], 25', '    mov dword [edi+RKIND], 1',
       f'    mov dword [edi+RLEN], {(root / "lib/io.inc").stat().st_size}',
       '    add edi, RDATA', '    mov esi, lib_io', f'    mov ecx, {(root / "lib/io.inc").stat().st_size}', '    rep movsb',
       '    mov edi, RECORDS+27*RSIZE', '    mov dword [edi], 0x6874616d', '    mov dword [edi+4], 0x636e692e',
       '    mov dword [edi+RPARENT], 25', '    mov dword [edi+RKIND], 1',
       f'    mov dword [edi+RLEN], {(root / "lib/math.inc").stat().st_size}',
       '    add edi, RDATA', '    mov esi, lib_math', f'    mov ecx, {(root / "lib/math.inc").stat().st_size}', '    rep movsb',
       '    mov edi, RECORDS+28*RSIZE', '    mov dword [edi], 0x6874616d', '    mov dword [edi+4], 0x7361632e',
       '    mov dword [edi+RPARENT], 25', '    mov dword [edi+RKIND], 1',
       f'    mov dword [edi+RLEN], {(root / "lib/math.cas").stat().st_size}',
       '    add edi, RDATA', '    mov esi, lib_mathcas', f'    mov ecx, {(root / "lib/math.cas").stat().st_size}', '    rep movsb',
       '    mov edi, RECORDS+29*RSIZE', '    mov dword [edi], 0x6c697475', '    mov dword [edi+4], 0x7361632e',
       '    mov dword [edi+RPARENT], 25', '    mov dword [edi+RKIND], 1',
       f'    mov dword [edi+RLEN], {(root / "lib/util.cas").stat().st_size}',
       '    add edi, RDATA', '    mov esi, lib_utilcas', f'    mov ecx, {(root / "lib/util.cas").stat().st_size}', '    rep movsb',
       "    cmp dword [0x68000], 'CASN'", '    jne .no_desktop',
       '    mov edi, RECORDS+30*RSIZE', '    mov dword [edi], 0x6b736564', '    mov dword [edi+4], 0x7361632e',
       '    mov dword [edi+RPARENT], ROOT_ID', '    mov dword [edi+RKIND], 1',
       f'    mov dword [edi+RLEN], {(root / "examples/castic/desktop.cas").stat().st_size}',
       '    add edi, RDATA', '    mov esi, desk_cas', f'    mov ecx, {(root / "examples/castic/desktop.cas").stat().st_size}', '    rep movsb',
       '.no_desktop:', '    mov edi, RECORDS+31*RSIZE', '    mov dword [edi], 0x6b736564', '    mov dword [edi+4], 0x7361632e',
       '    mov dword [edi+RPARENT], 25', '    mov dword [edi+RKIND], 1',
       f'    mov dword [edi+RLEN], {(root / "lib/desk.cas").stat().st_size}',
       '    add edi, RDATA', '    mov esi, lib_deskcas', f'    mov ecx, {(root / "lib/desk.cas").stat().st_size}', '    rep movsb',
       '    popad', '    ret', 
       "fs_docs_name db 'docs',0", 'fs_doc_table:']
for i,p in enumerate(files,5):
    data=p.read_bytes()
    assert 0 < len(data) <= 8000 and data.isascii() and len(p.name)<=31
    out += [f'    dd fs_doc_name_{i}, {len(p.name)}, fs_doc_data_{i}, {len(data)}']
for i,p in enumerate(files,5):
    out += [f"fs_doc_name_{i} db '{p.name}'", f'fs_doc_data_{i}:',
            f'    incbin "docs/on_disk/{p.name}"']
(root/'src/installed_docs.asm').write_text('\n'.join(out)+'\n')
print('Guías de instalación:',', '.join(p.name for p in files))
